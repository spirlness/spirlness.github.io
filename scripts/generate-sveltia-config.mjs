#!/usr/bin/env node
/**
 * Generate `public/admin/config.yml` for the local Sveltia CMS.
 *
 * The repo's zod schemas (`src/lib/content-schemas.ts`) are the single source
 * of truth for the content model. This script introspects them with
 * `z.toJSONSchema()` and fails loudly when the authored field mapping below
 * drifts from the schema key sets (a field added to the schema but not to the
 * CMS, or vice versa). `assertSchemaAlignment()` also pins the settings that
 * were smoke-tested against Sveltia 0.270.0:
 *
 *   - `output.omit_empty_optional_fields: true` and `output.yaml.quote: double`
 *     (Sveltia writes YAML itself; quoted strings keep dates as strings).
 *   - Date-like values use `widget: string` with a pattern. Sveltia's date
 *     picker discards the day for `YYYY-MM` and month widgets reformat values,
 *     so never use `widget: datetime` here.
 *   - `public_folder: '/'` with `media_folder: 'public'`; posts and projects
 *     override both with `{{slug}}` templates so uploads land in the same
 *     directories the sharp media pipeline scans.
 *
 * CLI:
 *   tsx scripts/generate-sveltia-config.mjs           # write the file
 *   tsx scripts/generate-sveltia-config.mjs --check   # fail if it is stale
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { stringify as stringifyYaml } from "yaml";
import { z } from "zod";
import {
  postFrontmatterSchema,
  projectSchema,
  updateSchema,
  updateIcons,
  postLanguages,
} from "../src/lib/content-schemas.ts";
import { CONTENT_SLUG_REGEX, CITATION_KEY_REGEX } from "../src/lib/content-id.ts";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const configPath = path.join(repoRoot, "public", "admin", "config.yml");
export const SITE_REPO = "spirlness/spirlness.github.io";

/**
 * Date patterns are deliberately written with `[0-9]` instead of `\d`: the
 * generated file is YAML, and character classes avoid backslash-escaping
 * surprises in YAML serializers and hand edits alike.
 */
export const POST_DATE_PATTERN = "^[0-9]{4}-[0-9]{2}-[0-9]{2}$";
export const MONTH_PATTERN = "^[0-9]{4}-[0-9]{2}$";

const YAML_HEADER = [
  "# Generated by scripts/generate-sveltia-config.mjs from src/lib/content-schemas.ts.",
  "# Do not edit by hand: run `npm run cms:config` to regenerate this file, and",
  "# `npm run cms:sync` to vendor the Sveltia bundle into the (gitignored) public/admin.",
  "",
].join("\n");

const DATE_HINT =
  "Stored verbatim as YAML text; the site schema validates the pattern.";

const slugPattern = CONTENT_SLUG_REGEX.source;
const bodyHint = `MDX source. Cite with [@key]; citation keys match ${CITATION_KEY_REGEX.source}.`;

function findField(collection, name) {
  return (collection?.fields ?? []).find((field) => field.name === name);
}

