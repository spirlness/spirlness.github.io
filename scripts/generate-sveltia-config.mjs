/** Build the config object without validating it (used by the validator itself). */
function createConfig() {
  return {
    backend: {
      // Local mode only: Sveltia never talks to GitHub for file operations
      // here; the repo name partitions its IndexedDB cache.
      name: "github",
      repo: SITE_REPO,
      branch: "master",
    },
    output: {
      omit_empty_optional_fields: true,
      yaml: {
        quote: "double",
      },
    },
    // Site-wide media settings: uploads land under public/ and are referenced
    // with site-root-relative URLs. Posts and projects override both below.
    media_folder: "public",
    public_folder: "/",
    slug: {
      encoding: "ascii",
      clean_accents: true,
    },
    collections: [
      {
        name: "posts",
        label: "Blog Posts",
        label_singular: "Blog Post",
        folder: "content/posts",
        media_folder: "/public/posts/{{slug}}",
        public_folder: "/posts/{{slug}}",
        extension: "mdx",
        format: "frontmatter",
        create: true,
        identifier_field: "title",
        slug: "{{slug}}",
        preview_path: "/blog/{{slug}}/",
        summary: "{{title}} — {{date}}",
        sortable_fields: ["date", "title"],
        fields: createPostFields(),
      },
      {
        name: "updates",
        label: "Timeline Updates",
        label_singular: "Update",
        folder: "content/updates",
        extension: "json",
        format: "json",
        create: true,
        identifier_field: "content",
        summary: "{{date}} — {{content}}",
        sortable_fields: ["date"],
        fields: createUpdateFields(),
      },
      {
        name: "projects",
        label: "Projects",
        label_singular: "Project",
        folder: "content/projects",
        media_folder: "/public/projects/{{slug}}",
        public_folder: "/projects/{{slug}}",
        extension: "json",
        format: "json",
        create: true,
        identifier_field: "id",
        slug: "{{slug}}",
        preview_path: "/projects/{{slug}}/",
        summary: "{{title}} ({{id}})",
        sortable_fields: ["date", "title"],
        fields: createProjectFields(),
      },
    ],
  };
}

/** Property key set the zod schema accepts, or a loud failure. */
function schemaKeys(schema, label) {
  let json;
  try {
    json = z.toJSONSchema(schema, { unrepresentable: "any" });
  } catch (error) {
    throw new Error(
      `[cms:config] z.toJSONSchema cannot introspect ${label}: ${
        error instanceof Error ? error.message : error
      }`
    );
  }
  const keys = json && typeof json === "object" ? Object.keys(json.properties ?? {}) : [];
  if (keys.length === 0) {
    throw new Error(`[cms:config] ${label} exposed no properties to align against.`);
  }
  return keys;
}

function schemaPropertyKeys(schema, property, label) {
  const json = z.toJSONSchema(schema, { unrepresentable: "any" });
  const propertySchema = json.properties?.[property];
  if (!propertySchema) {
    throw new Error(`[cms:config] ${label} has no "${property}" property to introspect.`);
  }
  return Object.keys(propertySchema.properties ?? {});
}

/**
 * Fail loudly unless the authored CMS field mapping matches the zod schemas
 * and the smoke-validated Sveltia settings. Exported for the unit test; also
 * accepts a config object so tests can prove drift is detected.
 */
export function assertSchemaAlignment(config = createConfig()) {
  const problems = [];
  const collections = Array.isArray(config.collections) ? config.collections : [];
  const collection = (name) => collections.find((entry) => entry?.name === name);

  const compareKeys = (name, expected, extraKeys) => {
    const current = collection(name);
    if (!current) {
      problems.push(`missing collection "${name}"`);
      return;
    }
    const authored = (current.fields ?? []).map((field) => field.name);
    const missing = expected.filter((key) => !authored.includes(key));
    const extra = authored.filter(
      (key) => !expected.includes(key) && !extraKeys.includes(key)
    );
    if (missing.length > 0) {
      problems.push(`${name}: missing field(s) ${missing.join(", ")}`);
    }
    if (extra.length > 0) {
      problems.push(`${name}: field(s) absent from the zod schema: ${extra.join(", ")}`);
    }
    for (const key of extraKeys) {
      if (!authored.includes(key)) {
        problems.push(`${name}: missing virtual field "${key}"`);
      }
    }
  };

  compareKeys("posts", schemaKeys(postFrontmatterSchema, "postFrontmatterSchema"), ["body"]);
  compareKeys("projects", schemaKeys(projectSchema, "projectSchema"), []);
  compareKeys("updates", schemaKeys(updateSchema, "updateSchema"), []);

  // Body is a Sveltia virtual field: raw MDX, not frontmatter.
  const posts = collection("posts");
  const body = findField(posts, "body");
  if (!body) {
    problems.push("posts: missing body field");
  } else {
    if (body.widget !== "richtext") {
      problems.push('posts.body: widget must be "richtext"');
    }
    if (JSON.stringify(body.modes) !== JSON.stringify(["raw"])) {
      problems.push("posts.body: modes must be [raw]");
    }
  }

  // Date-like values must be string widgets with patterns, never date pickers.
  for (const current of collections) {
    for (const field of current.fields ?? []) {
      if (field.widget === "datetime") {
        problems.push(
          `${current.name}.${field.name}: datetime widgets discard or reformat values; use widget: string with a pattern`
        );
      }
    }
  }
  const expectStringPattern = (collectionName, fieldName, pattern) => {
    const field = findField(collection(collectionName), fieldName);
    if (!field) {
      problems.push(`${collectionName}: missing ${fieldName} field`);
      return;
    }
    if (field.widget !== "string") {
      problems.push(`${collectionName}.${fieldName}: widget must be "string"`);
    }
    if (field.pattern?.[0] !== pattern) {
      problems.push(
        `${collectionName}.${fieldName}: pattern must be ${JSON.stringify(pattern)}`
      );
    }
  };
  expectStringPattern("posts", "date", POST_DATE_PATTERN);
  expectStringPattern("posts", "lastUpdated", POST_DATE_PATTERN);
  expectStringPattern("updates", "date", MONTH_PATTERN);
  expectStringPattern("projects", "date", MONTH_PATTERN);
  expectStringPattern("projects", "lastModified", POST_DATE_PATTERN);

  // Drafts: optional boolean defaulting to false on posts and projects only.
  for (const name of ["posts", "projects"]) {
    const draft = findField(collection(name), "draft");
    if (!draft) {
      problems.push(`${name}: missing draft field`);
      continue;
    }
    if (draft.widget !== "boolean") {
      problems.push(`${name}.draft: widget must be "boolean"`);
    }
    if (draft.required !== false) {
      problems.push(`${name}.draft: must be required: false`);
    }
    if (draft.default !== false) {
      problems.push(`${name}.draft: must default to false`);
    }
  }
  if (findField(collection("updates"), "draft")) {
    problems.push("updates: draft is not part of updateSchema");
  }

  // Tags: posts use the content slug regex; project tags are display-only.
  const postTags = findField(posts, "tags");
  if (postTags?.field?.pattern?.[0] !== CONTENT_SLUG_REGEX.source) {
    problems.push(
      `posts.tags: nested pattern must equal CONTENT_SLUG_REGEX (${CONTENT_SLUG_REGEX.source})`
    );
  }
  const projectId = findField(collection("projects"), "id");
  if (projectId?.pattern?.[0] !== CONTENT_SLUG_REGEX.source) {
    problems.push(
      `projects.id: pattern must equal CONTENT_SLUG_REGEX (${CONTENT_SLUG_REGEX.source})`
    );
  }

  // Icon options are imported from updateIcons, never hardcoded.
  const iconOptions = (findField(collection("updates"), "icon")?.options ?? []).map(
    (option) => (typeof option === "string" ? option : option?.value)
  );
  if (JSON.stringify(iconOptions) !== JSON.stringify([...updateIcons])) {
    problems.push(
      `updates.icon: options must equal updateIcons (${updateIcons.join(", ")})`
    );
  }

  // Language options come from postLanguages.
  const langOptions = (findField(posts, "lang")?.options ?? []).map(
    (option) => (typeof option === "string" ? option : option?.value)
  );
  if (JSON.stringify(langOptions) !== JSON.stringify([...postLanguages])) {
    problems.push(`posts.lang: options must equal postLanguages (${postLanguages.join(", ")})`);
  }

  // The links object must expose exactly the keys projectSchema accepts.
  const linksField = findField(collection("projects"), "links");
  if (!linksField) {
    problems.push("projects: missing links field");
  } else {
    const expectedLinks = schemaPropertyKeys(projectSchema, "links", "projectSchema");
    const authoredLinks = (linksField.fields ?? []).map((field) => field.name);
    for (const key of expectedLinks) {
      if (!authoredLinks.includes(key)) {
        problems.push(`projects.links: missing "${key}"`);
      }
    }
    for (const key of authoredLinks) {
      if (!expectedLinks.includes(key)) {
        problems.push(`projects.links: "${key}" is not in projectSchema`);
      }
    }
  }

  // Smoke-validated global settings.
  if (config.backend?.name !== "github") {
    problems.push('backend.name must be "github" (IndexedDB partition)');
  }
  if (!config.backend?.repo) {
    problems.push("backend.repo must be set (Sveltia uses it to partition IndexedDB)");
  }
  if (config.media_folder !== "public") {
    problems.push('media_folder must be "public"');
  }
  if (config.public_folder !== "/") {
    problems.push('public_folder must be "/"');
  }
  if (config.slug?.encoding !== "ascii") {
    problems.push('slug.encoding must be "ascii"');
  }
  if (config.output?.omit_empty_optional_fields !== true) {
    problems.push("output.omit_empty_optional_fields must be true");
  }
  if (config.output?.yaml?.quote !== "double") {
    problems.push('output.yaml.quote must be "double"');
  }

  const expectedMedia = {
    posts: { media_folder: "/public/posts/{{slug}}", public_folder: "/posts/{{slug}}" },
    projects: {
      media_folder: "/public/projects/{{slug}}",
      public_folder: "/projects/{{slug}}",
    },
  };
  for (const [name, expected] of Object.entries(expectedMedia)) {
    const current = collection(name);
    if (!current) continue;
    if (current.media_folder !== expected.media_folder) {
      problems.push(
        `${name}.media_folder must be ${JSON.stringify(expected.media_folder)}`
      );
    }
    if (current.public_folder !== expected.public_folder) {
      problems.push(
        `${name}.public_folder must be ${JSON.stringify(expected.public_folder)}`
      );
    }
  }

  if (problems.length > 0) {
    throw new Error(
      `[cms:config] Sveltia config drifted from the content schemas:\n  - ${problems.join(
        "\n  - "
      )}`
    );
  }
}

/** Build and validate the config object (no YAML serialization). */
export function buildConfig() {
  const config = createConfig();
  assertSchemaAlignment(config);
  return config;
}

/** Deterministic YAML text for public/admin/config.yml. */
export function generateConfigYaml() {
  return `${YAML_HEADER}${stringifyYaml(buildConfig(), { lineWidth: 0 })}`;
}

function printUsage() {
  console.log(
    [
      "Usage: tsx scripts/generate-sveltia-config.mjs [--check]",
      "",
      "  (no flags)  write public/admin/config.yml from the zod schemas",
      "  --check     exit non-zero when the on-disk file differs from generated output",
    ].join("\n")
  );
}

function runCli() {
  const args = process.argv.slice(2);
  const unknown = args.filter((arg) => arg !== "--check" && arg !== "--help" && arg !== "-h");
  if (unknown.length > 0) {
    console.error(`[cms:config] unknown argument(s): ${unknown.join(", ")}`);
    printUsage();
    process.exit(2);
  }
  if (args.includes("--help") || args.includes("-h")) {
    printUsage();
    return;
  }

  const expected = generateConfigYaml();
  const relativePath = path.relative(repoRoot, configPath);

  if (args.includes("--check")) {
    if (!fs.existsSync(configPath)) {
      console.error(`[cms:config] ${relativePath} does not exist; run npm run cms:config.`);
      process.exit(1);
    }
    const onDisk = fs.readFileSync(configPath, "utf8");
    if (onDisk !== expected) {
      console.error(
        `[cms:config] ${relativePath} is stale (differs from generated output). Run npm run cms:config.`
      );
      process.exit(1);
    }
    console.log(`[cms:config] ${relativePath} is up to date.`);
    return;
  }

  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, expected);
  const config = buildConfig();
  console.log(
    `[cms:config] wrote ${relativePath}: ${config.collections.length} collections ` +
      `(${config.collections.map((entry) => entry.name).join(", ")}), ` +
      `media_folder "${config.media_folder}", public_folder "${config.public_folder}".`
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  runCli();
}
